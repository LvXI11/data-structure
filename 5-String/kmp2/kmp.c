#include<string.h>

/* ============================================================
 * get_next —— 递推（用已经算好的 next 值去算下一格）
 *
 *   p[]    模式串
 *   next[] 输出数组（长度至少 m）
 *   m      模式串长度
 *
 * 约定：next[0] = -1
 * 定义：next[j] = p[0..j-1] 里「最长相等真前后缀」的长度
 * ============================================================ */
void get_next(const char p[], int next[], int m)
{
    next[0] = -1;               /* 约定：长度 0 的串没有前后缀，用 -1 表示"退无可退" */

    int j = 0;                  /* j：当前已经算完 next[j] 的那个下标；
                                   循环体里干的事是"算 next[j+1]" */
    int k = -1;                 /* k：当前"最长相等前后缀"的长度（= next[j]）；
                                   同时也是"下一个要拿来比"的字符下标 */

    while (j < m - 1) {         /* 要填 next[1]..next[m-1]，所以 j 最多推进到 m-2 */

        if (k == -1 || p[j] == p[k]) {
            /* 【两种情况都可以让长度 +1】
               ① k == -1：候选长度已经退到"没有"了 → 只能从长度 0 重新开始
               ② p[j] == p[k]：前缀的下一个字符 == 后缀的下一个字符
                               → 原来的长度 k 可以延长成 k+1 */

            j++;                /* 推进到下一个要填的位置 */
            k++;                /* 长度 +1 */
            next[j] = k;        /* 前 j 个字符的最长相等前后缀长度就是 k */

        } else {
            /* 【配不上 → 退而求其次】
               p[j] != p[k]：长度 k 这个候选废了
               但不用从头重算 —— "次长的候选"正好就是 next[k]
               ★ 这就是 k = next[k] 的全部含义 */
            k = next[k];
        }
    }
}